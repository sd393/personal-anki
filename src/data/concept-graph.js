export const CONCEPTS_BY_SLUG = Object.fromEntries(CONCEPTS.map((c) => [c.slug, c]));

/** Ordered bucket/section structure for rendering the dashboard. */
export const SECTIONS = (() => {
  const out = [];
  for (const c of CONCEPTS) {
    let last = out[out.length - 1];
    if (!last || last.bucket !== c.bucket || last.section !== c.section) {
      last = { bucket: c.bucket, section: c.section, slugs: [] };
      out.push(last);
    }
    last.slugs.push(c.slug);
  }
  return out;
})();
